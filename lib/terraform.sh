# OpenTofu wrapper. Each cluster gets a small root module in <cluster>/tofu
# that calls the shipped module in terraform/. State stays local in the
# cluster directory. Credentials reach the provider only through the
# PROXMOX_VE_* environment variables, never through variables or state.

# Globals defined here are used by the other libraries and okd-pve.
# shellcheck disable=SC2034

[[ -n ${_OKD_PVE_TERRAFORM_LOADED:-} ]] && return 0
_OKD_PVE_TERRAFORM_LOADED=1

TF_VM_ADDR='module.okd.proxmox_virtual_environment_vm.node'

tf_write_root() {
	mkdir -p "${TOFU_DIR}"
	local tmp_dir tmp_hcl=null
	tmp_dir=$(cfg '.proxmox.tmp_dir')
	[[ -n ${tmp_dir} ]] && tmp_hcl="\"$(resolve_path "${tmp_dir}")\""
	cat >"${TOFU_DIR}/main.tf" <<EOF
# Generated by okd-pve. Do not edit; changes are overwritten.
terraform {
  required_providers {
    proxmox = {
      source  = "${PROXMOX_PROVIDER_SOURCE}"
      version = "${PROXMOX_PROVIDER_VERSION}"
    }
  }
}

locals {
  cfg = jsondecode(file("\${path.module}/cluster.auto.json"))
}

# Endpoint, token and TLS settings come from PROXMOX_VE_* variables.
provider "proxmox" {
  tmp_dir = ${tmp_hcl}
}

module "okd" {
  source = "${OKD_PVE_ROOT}/terraform"

  cluster_name       = local.cfg.cluster_name
  pool_id            = local.cfg.pool_id
  vm_storage         = local.cfg.vm_storage
  efi_storage        = local.cfg.efi_storage
  iso_storage        = local.cfg.iso_storage
  iso_storage_shared = local.cfg.iso_storage_shared
  bridge             = local.cfg.bridge
  vlan_id            = local.cfg.vlan_id
  cpu_type           = local.cfg.cpu_type
  bios               = local.cfg.bios
  machine            = local.cfg.machine
  upload_timeout     = local.cfg.upload_timeout
  tags               = local.cfg.tags
  ha                 = local.cfg.ha
  isos               = local.cfg.isos
  nodes              = local.cfg.nodes
}

output "nodes" {
  value = module.okd.nodes
}
EOF
}

# tf_iso_storage_shared: ask Proxmox whether the ISO storage is shared.
tf_iso_storage_shared() {
	local host info
	host=$(cfg '.proxmox.nodes' | head -n1)
	info=$(pve_node_storage "${host}" 2>/dev/null) || {
		echo false
		return
	}
	jq -r --arg s "$(cfg '.proxmox.iso_storage')" \
		'[.[] | select(.storage == $s) | .shared // 0] | if .[0] == 1 then "true" else "false" end' <<<"${info}"
}

# tf_isos_json: ISO map from the ISO registry in the state directory.
# Each entry: {"path": ..., "file_name": ..., "hosts": [...]}.
tf_isos_json() {
	if [[ -f ${STATE_DIR}/isos.json ]]; then
		cat "${STATE_DIR}/isos.json"
	else
		echo '{}'
	fi
}

# tf_iso_register <key> <path> <hosts-json-array>
# tf_iso_file_name <key> <path>: name on the Proxmox storage. The build time
# is part of it, so a rebuilt ISO gets a new name and OpenTofu replaces the
# upload (a changed file under the same name would not be noticed).
tf_iso_file_name() {
	local t stamp
	t=$(file_mtime "$2" 2>/dev/null) || t=$(date +%s)
	stamp=$(date -d "@${t}" +%Y%m%d%H%M 2>/dev/null || date -r "${t}" +%Y%m%d%H%M)
	printf 'okd-pve-%s-%s-%s.iso' "${CLUSTER_NAME}" "$1" "${stamp}"
}

tf_iso_register() {
	state_init
	local isos
	isos=$(tf_isos_json)
	jq -c --arg k "$1" --arg p "$2" --argjson h "$3" \
		--arg f "$(tf_iso_file_name "$1" "$2")" \
		'.[$k] = {path: $p, file_name: $f, hosts: $h}' <<<"${isos}" >"${STATE_DIR}/isos.json"
}

tf_iso_unregister() {
	[[ -f ${STATE_DIR}/isos.json ]] || return 0
	jq -c --arg k "$1" 'del(.[$k])' "${STATE_DIR}/isos.json" >"${STATE_DIR}/isos.json.tmp"
	mv "${STATE_DIR}/isos.json.tmp" "${STATE_DIR}/isos.json"
}

# tf_node_isos: {"hostname": "iso-key"} of nodes that still boot from an ISO.
tf_node_isos() {
	if [[ -f ${STATE_DIR}/node-isos.json ]]; then
		cat "${STATE_DIR}/node-isos.json"
	else
		echo '{}'
	fi
}

# tf_node_isos_set <json>
tf_node_isos_set() {
	state_init
	jq -c . <<<"$1" >"${STATE_DIR}/node-isos.json"
}

# tf_guard_existing <new-vars-file>: refuse changes that would make OpenTofu
# replace VMs that already exist (VMID, MAC or host of a node changed, e.g.
# because a node group was inserted before others or vmid_start changed).
tf_guard_existing() {
	local old=${TOFU_DIR}/cluster.auto.json changed
	[[ -f ${old} ]] && tf_has_state || return 0
	changed=$(jq -r --slurpfile new "$1" '
		.nodes as $o | $new[0].nodes as $n
		| [$o | keys[] | select($n[.] != null)
		   | select($o[.].vmid != $n[.].vmid or $o[.].mac != $n[.].mac or $o[.].host != $n[.].host)
		   | "\(.): VMID \($o[.].vmid)->\($n[.].vmid), MAC \($o[.].mac)->\($n[.].mac), host \($o[.].host)->\($n[.].host)"]
		| .[]' "${old}")
	[[ -z ${changed} ]] && return 0
	local l
	while IFS= read -r l; do log_error "${l}"; done <<<"${changed}"
	die "${EXIT_CONFIG}" "This configuration change would recreate existing VMs." \
		"Revert it. New node groups go to the end of node_groups (or get an explicit vmid_offset)."
}

tf_write_vars() {
	local shared
	shared=$(tf_iso_storage_shared)
	local efi
	efi=$(cfg '.proxmox.efi_storage')
	[[ -n ${efi} ]] || efi=$(cfg '.proxmox.vm_storage')
	nodes_json | jq --arg cluster "${CLUSTER_NAME}" --arg pool "$(pool_name)" \
		--slurpfile c "${CONFIG_JSON}" --arg efi "${efi}" --argjson shared "${shared}" \
		--argjson isos "$(tf_isos_json)" --argjson node_isos "$(tf_node_isos)" '
		$c[0] as $c | {
			cluster_name: $cluster,
			pool_id: $pool,
			vm_storage: $c.proxmox.vm_storage,
			efi_storage: $efi,
			iso_storage: $c.proxmox.iso_storage,
			iso_storage_shared: $shared,
			bridge: $c.proxmox.bridge,
			vlan_id: $c.proxmox.vlan_tag,
			cpu_type: $c.proxmox.cpu_type,
			bios: $c.proxmox.bios,
			machine: $c.proxmox.machine,
			upload_timeout: $c.proxmox.upload_timeout,
			tags: $c.proxmox.tags,
			ha: $c.proxmox.ha,
			isos: $isos,
			nodes: (map({key: .name, value: {
				host, vmid, mac, cpu, memory_mib, disk_gib, boot_serial, roles,
				iso: ($node_isos[.name] // ""),
				data_disks
			}}) | from_entries)
		}' >"${TOFU_DIR}/cluster.auto.json.new"
	tf_guard_existing "${TOFU_DIR}/cluster.auto.json.new"
	mv "${TOFU_DIR}/cluster.auto.json.new" "${TOFU_DIR}/cluster.auto.json"
}

# tofu_run <args...>: run tofu in the cluster root module. SIGINT reaches
# tofu (same process group) and lets it stop gracefully and save state.
tofu_run() {
	TF_IN_AUTOMATION=1 TF_PLUGIN_CACHE_DIR=${TF_PLUGIN_CACHE_DIR:-${XDG_CACHE_HOME:-${HOME}/.cache}/okd-pve/tofu-plugins} \
		"${TOFU}" -chdir="${TOFU_DIR}" "$@"
}

tf_init() {
	mkdir -p "${TF_PLUGIN_CACHE_DIR:-${XDG_CACHE_HOME:-${HOME}/.cache}/okd-pve/tofu-plugins}"
	tf_write_root
	if [[ -d ${TOFU_DIR}/.terraform && -f ${TOFU_DIR}/.terraform.lock.hcl ]]; then
		return 0
	fi
	log_info "Initializing OpenTofu (provider ${PROXMOX_PROVIDER_SOURCE} ${PROXMOX_PROVIDER_VERSION})"
	run_logged tofu_run init -input=false -no-color ||
		die "${EXIT_ERROR}" "tofu init failed." "Check network access to registry.opentofu.org and ${LOG_FILE}."
}

# tf_plan [extra-args...]: print a readable plan (used by --dry-run).
tf_plan() {
	tf_init
	tf_write_vars
	log_info "OpenTofu plan:"
	run_visible '      ' tofu_run plan -input=false -no-color -compact-warnings "$@" ||
		die "${EXIT_ERROR}" "tofu plan failed." "See the plan output above and ${LOG_FILE}."
}

# tf_apply [extra-args...]
tf_apply() {
	tf_init
	tf_write_vars
	local start=${SECONDS}
	run_visible '      | ' tofu_run apply -input=false -no-color -auto-approve -compact-warnings "$@" ||
		die "${EXIT_ERROR}" "tofu apply failed." \
			"Fix the cause shown above and re-run the same command; OpenTofu continues from its state."
	log_ok "OpenTofu apply finished in $(elapsed "${start}")"
}

tf_destroy() {
	tf_init
	tf_write_vars
	run_visible '      | ' tofu_run destroy -input=false -no-color -auto-approve -compact-warnings "$@" ||
		die "${EXIT_ERROR}" "tofu destroy failed." "Fix the cause shown above and re-run destroy."
}

tf_has_state() {
	[[ -f ${TOFU_DIR}/terraform.tfstate ]] &&
		jq -e '(.resources // []) | length > 0' "${TOFU_DIR}/terraform.tfstate" >/dev/null 2>&1
}

tf_vm_target() {
	printf -- '-target=%s["%s"]' "${TF_VM_ADDR}" "$1"
}
